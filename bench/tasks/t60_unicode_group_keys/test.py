from solution import solve

assert solve(["Café", "cafe", "Tea"]) == [["Café", "cafe"], ["Tea"]]
assert solve(["Ａ", "a", "ß", "ss"]) == [["Ａ", "a"], ["ß", "ss"]]
assert solve([]) == []
assert solve([""]) == [[""]]
assert solve(["", " ", "\t"]) == [["", " ", "\t"]]
assert solve(["A", "a"]) == [["A", "a"]]
assert solve(["a", "A", "a"]) == [["a", "A", "a"]]
assert solve(["é", "e"]) == [["é", "e"]]
assert solve(["e\u0301", "e"]) == [["e\u0301", "e"]]
assert solve(["É", "e"]) == [["É", "e"]]
assert solve(["İ", "i"]) == [["İ", "i"]]
assert solve(["ß", "ss"]) == [["ß", "ss"]]
assert solve(["ﬃ", "ffi"]) == [["ﬃ", "ffi"]]
assert solve(["Ａ", "a"]) == [["Ａ", "a"]]
assert solve(["１", "1"]) == [["１", "1"]]
assert solve(["a  b", "a b"]) == [["a  b", "a b"]]
assert solve(["a\tb", "a b"]) == [["a\tb", "a b"]]
assert solve([" a ", "a"]) == [[" a ", "a"]]
assert solve(["\u00a0a\u00a0", "a"]) == [["\u00a0a\u00a0", "a"]]
assert solve(["a", "b", "A"]) == [["a", "A"], ["b"]]
assert solve(["b", "a", "A"]) == [["b"], ["a", "A"]]
assert solve(["x", "y", "X", "Y"]) == [["x", "X"], ["y", "Y"]]
assert solve(["Å", "a"]) == [["Å", "a"]]
assert solve(["A\u030a", "a"]) == [["A\u030a", "a"]]
assert solve(["Œ", "oe"]) == [["Œ"], ["oe"]]
assert solve(["a-b", "a b"]) == [["a-b"], ["a b"]]
