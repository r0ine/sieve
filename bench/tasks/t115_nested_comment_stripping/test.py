from solution import solve


assert solve("a/* x */b") == "ab"
assert solve("x//y\nz") == "x\nz"
assert solve("\"/*x*/\"") == "\"/*x*/\""
assert solve("") == ""
assert solve("plain") == "plain"
assert solve("/*a*/") == ""
assert solve("/*a/*b*/c*/x") == "x"
assert solve("a/*x") == "a"
assert solve("a//x") == "a"
assert solve("a//x\n") == "a\n"
assert solve("//x\n//y\nz") == "\n\nz"
assert solve("/*//*/x") == ""
assert solve("///*x*/\ny") == "\ny"
assert solve("'//'") == "'//'"
assert solve("a*/b") == "a*/b"
assert solve("a/**/b") == "ab"
assert solve("a/*x*/ /*y*/b") == "a b"
assert solve("a//x\r\nb") == "a\nb"
assert solve("é/*😀*/ß") == "éß"
assert solve("/* one\n two */x") == "x"
assert solve("/*/*/*x*/*/*/z") == "z"
assert solve("'/*'/*x*/'*/'") == "'/*''*/'"
assert solve("\"//\"//x\nz") == "\"//\"\nz"
assert solve("'a\\'//b'") == "'a\\'//b'"
assert solve("\"a\\\"/*b*/\"") == "\"a\\\"/*b*/\""
assert solve("/* unterminated //") == ""
assert solve("x/*a*/y//b\nz") == "xy\nz"
assert solve("/*a*/\"//\"") == "\"//\""
assert solve("//x\n/*y*/z") == "\nz"
