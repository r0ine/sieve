from solution import solve


assert solve([], []) == []
assert solve(["A"], []) == [("A", 0, 0, 0)]
assert solve(["B","A"], []) == [("A", 0, 0, 0), ("B", 0, 0, 0)]
assert solve(["A","B"], [["A","B",1,0]]) == [("A", 3, 1, 1), ("B", 0, -1, 0)]
assert solve(["A","B"], [["A","B",0,1]]) == [("B", 3, 1, 1), ("A", 0, -1, 0)]
assert solve(["A","B"], [["A","B",0,0]]) == [("A", 1, 0, 0), ("B", 1, 0, 0)]
assert solve(["A","B"], [["A","B",2,2]]) == [("A", 1, 0, 2), ("B", 1, 0, 2)]
assert solve(["A","B"], [["A","B",3,1]]) == [("A", 3, 2, 3), ("B", 0, -2, 1)]
assert solve(["A","B"], [["A","B",1,3]]) == [("B", 3, 2, 3), ("A", 0, -2, 1)]
assert solve(["A","B"], [["A","B",2,1],["B","A",1,0]]) == [("A", 3, 0, 2), ("B", 3, 0, 2)]
assert solve(["A","B"], [["A","B",1,0],["B","A",0,1]]) == [("A", 6, 2, 2), ("B", 0, -2, 0)]
assert solve(["A","B"], [["A","B",0,0],["B","A",0,0]]) == [("A", 2, 0, 0), ("B", 2, 0, 0)]
assert solve(["A","B"], [["A","B",0,0],["A","B",1,0]]) == [("A", 4, 1, 1), ("B", 1, -1, 0)]
assert solve(["A","B","C"], []) == [("A", 0, 0, 0), ("B", 0, 0, 0), ("C", 0, 0, 0)]
assert solve(["A","B","C"], [["A","B",1,0]]) == [("A", 3, 1, 1), ("C", 0, 0, 0), ("B", 0, -1, 0)]
assert solve(["A","B","C"], [["A","B",0,0],["B","C",0,0]]) == [("B", 2, 0, 0), ("A", 1, 0, 0), ("C", 1, 0, 0)]
assert solve(["A","B","C"], [["A","B",1,0],["B","C",1,0],["C","A",1,0]]) == [("A", 3, 0, 1), ("B", 3, 0, 1), ("C", 3, 0, 1)]
assert solve(["A","B","C"], [["A","B",2,0],["B","C",1,0],["C","A",1,0]]) == [("A", 3, 1, 2), ("C", 3, 0, 1), ("B", 3, -1, 1)]
assert solve(["A","B","C"], [["A","B",1,0],["B","C",2,0],["C","A",1,0]]) == [("B", 3, 1, 2), ("A", 3, 0, 1), ("C", 3, -1, 1)]
assert solve(["A","B","C"], [["A","B",1,0],["A","C",1,0]]) == [("A", 6, 2, 2), ("B", 0, -1, 0), ("C", 0, -1, 0)]
assert solve(["A","B","C"], [["A","B",0,1],["A","C",0,1]]) == [("B", 3, 1, 1), ("C", 3, 1, 1), ("A", 0, -2, 0)]
assert solve(["A","B","C"], [["A","B",3,2],["B","C",2,1],["C","A",1,0]]) == [("B", 3, 0, 4), ("A", 3, 0, 3), ("C", 3, 0, 2)]
assert solve(["A","B","C"], [["A","B",1,0],["B","C",2,1],["C","A",3,2]]) == [("C", 3, 0, 4), ("A", 3, 0, 3), ("B", 3, 0, 2)]
assert solve(["é","e"], [["é","e",0,0]]) == [("e", 1, 0, 0), ("é", 1, 0, 0)]
assert solve(["Z","A"], [["Z","A",0,0]]) == [("A", 1, 0, 0), ("Z", 1, 0, 0)]
assert solve(["A","B"], [["A","B",1000000000000,0]]) == [("A", 3, 1000000000000, 1000000000000), ("B", 0, -1000000000000, 0)]
assert solve(["A","B","C"], [["A","B",0,0],["A","C",0,0],["B","C",0,0]]) == [("A", 2, 0, 0), ("B", 2, 0, 0), ("C", 2, 0, 0)]
assert solve(["A","B","C"], [["A","B",1,1],["B","C",2,2],["C","A",3,3]]) == [("C", 2, 0, 5), ("A", 2, 0, 4), ("B", 2, 0, 3)]
assert solve(['A', 'B'], [('A', 'B', 10**30, 0)]) == [('A', 3, 10**30, 10**30), ('B', 0, -(10**30), 0)]
