assert solve([[0, 5, 0], [1, 1, -1]]) == [[0, 5], [1, 6]]
assert solve([[2, 2, 0], [1, 1, 0]]) == [[1, 2], [0, 4]]
assert solve([[0, 2, 0], [2, 1, -1]]) == [[0, 2], [1, 3]]
assert solve([[0, 2, 0], [1, 1, -1], [1, 1, -2]]) == [[0, 2], [2, 3], [1, 4]]
assert solve([[5, 1, 0], [0, 2, 1]]) == [[1, 2], [0, 6]]
assert solve([[0, 1, 0], [10, 2, 0]]) == [[0, 1], [1, 12]]
assert solve([[0, 1, 1], [0, 1, -1], [0, 1, 0]]) == [[1, 1], [2, 2], [0, 3]]
assert solve([[1, 1, 0], [1, 2, 0], [1, 3, 0]]) == [[0, 2], [1, 4], [2, 7]]
assert solve([[0, 4, 0], [1, 1, 5], [2, 1, -1]]) == [[0, 4], [2, 5], [1, 6]]
assert solve([[0, 1, 0], [1, 1, 0], [2, 1, 0]]) == [[0, 1], [1, 2], [2, 3]]
assert solve([[0, 1, 0], [0, 1, 0], [0, 1, 0]]) == [[0, 1], [1, 2], [2, 3]]
assert solve([[0, 10, 0], [0, 1, -1]]) == [[1, 1], [0, 11]]
assert solve([[2, 1, 0], [2, 1, -1], [2, 1, 1]]) == [[1, 3], [0, 4], [2, 5]]
assert solve([[0, 1, 10], [0, 1, -10]]) == [[1, 1], [0, 2]]
assert solve([[0, 2, 0], [0, 1, 1], [1, 1, -1]]) == [[0, 2], [2, 3], [1, 4]]
assert solve([[0, 1, 0], [5, 1, 0], [3, 1, 0]]) == [[0, 1], [2, 4], [1, 6]]
assert solve([[100, 1, 0]]) == [[0, 101]]
assert solve([[0, 1000000000000, 0], [1, 1, 0]]) == [[0, 1000000000000], [1, 1000000000001]]
