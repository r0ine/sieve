from solution import solve

assert solve('a,"b,c"\nx,y') == [["a", "b,c"], ["x", "y"]]
assert solve('""\n') == [[""]]
assert solve("") == []
assert solve("a") == [["a"]]
assert solve("a,b") == [["a", "b"]]
assert solve("a,") == [["a", ""]]
assert solve(",") == [["", ""]]
assert solve(",,") == [["", "", ""]]
assert solve("\n") == [[""]]
assert solve("\r\n") == [[""]]
assert solve("a\n") == [["a"]]
assert solve("a\r\n") == [["a"]]
assert solve("a\n\n") == [["a"], [""]]
assert solve("a\r\n\r\n") == [["a"], [""]]
assert solve('"a"') == [["a"]]
assert solve('"a,b"') == [["a,b"]]
assert solve('"a""b"') == [['a"b']]
assert solve('""""') == [['"']]
assert solve('"a\nb"') == [["a\nb"]]
assert solve('"a\r\nb"') == [["a\r\nb"]]
assert solve('"a\nb",c') == [["a\nb", "c"]]
assert solve('a,""') == [["a", ""]]
assert solve('a,"",') == [["a", "", ""]]
assert solve(' a , b ') == [[" a ", " b "]]
assert solve("é,中") == [["é", "中"]]
assert solve('a\n"b,c"\r\nd') == [["a"], ["b,c"], ["d"]]
assert solve('a\n"b"') == [["a"], ["b"]]
