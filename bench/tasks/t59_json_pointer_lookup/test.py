from solution import solve

assert solve({"a": [10, None]}, ["/a/1", "/a/2"]) == [[True, None], [False, None]]
assert solve({"a/b": 3}, ["/a~1b", ""]) == [[True, 3], [True, {"a/b": 3}]]
assert solve(None, [""]) == [[True, None]]
assert solve(None, ["/x"]) == [[False, None]]
assert solve({}, [""]) == [[True, {}]]
assert solve({}, ["/"]) == [[False, None]]
assert solve({"": 1}, ["/"]) == [[True, 1]]
assert solve({"0": 7}, ["/0"]) == [[True, 7]]
assert solve([7], ["/0"]) == [[True, 7]]
assert solve([7], ["/1"]) == [[False, None]]
assert solve([7], ["/00"]) == [[False, None]]
assert solve([7], ["/+0"]) == [[False, None]]
assert solve([7], ["/-"]) == [[False, None]]
assert solve([7], ["/"]) == [[False, None]]
assert solve([7], ["/-1"]) == [[False, None]]
assert solve({"a/b": 2}, ["/a~1b"]) == [[True, 2]]
assert solve({"a~b": 2}, ["/a~0b"]) == [[True, 2]]
assert solve({"a~1b": 2}, ["/a~01b"]) == [[True, 2]]
assert solve({"a/b": 2}, ["/a~01b"]) == [[False, None]]
assert solve({"a": {"b": 3}}, ["/a/b"]) == [[True, 3]]
assert solve({"a": [4]}, ["/a/0"]) == [[True, 4]]
assert solve({"a": []}, ["/a/0"]) == [[False, None]]
assert solve({"a": None}, ["/a/x"]) == [[False, None]]
assert solve({"a": 0}, ["/a/x"]) == [[False, None]]
assert solve({"a": False}, ["/a"]) == [[True, False]]
assert solve({"a": {"": [9]}}, ["/a//0"]) == [[True, 9]]
